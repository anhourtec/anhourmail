/**
 * CLAUDE.md rule 53: brand assets have one source, packages/ui/assets/brand. This copies them into each app's
 * public/ folder (Next serves only from there). `--check` fails when a copy is missing or differs, or when an app
 * still holds a brand file that was removed from the source. Sub-folders (e.g. `print/` PNGs for documents) and
 * the README stay in the source only.
 *
 * It also writes the email logo module (`packages/adapters/src/mail/logo.generated.ts`) from `email/*.png` — base64
 * plus display size, so system emails embed the logo as an inline attachment wherever the code is bundled — and
 * `--check` fails when that module is stale. The PNGs come from `node scripts/render-email-logo.mjs`.
 */
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";

const SRC = "packages/ui/assets/brand";
const TARGETS = ["apps/web/public", "apps/site/public"];
const check = process.argv.includes("--check");
const files = readdirSync(SRC).filter((f) => f !== "README.md" && statSync(path.join(SRC, f)).isFile());
// Brand files that used to be synced; an app copy left behind would still be served.
const RETIRED = ["favicon-96x96.png"];
const drift = [];

for (const target of TARGETS) {
  if (!check) mkdirSync(target, { recursive: true });
  for (const f of files) {
    const from = path.join(SRC, f);
    const to = path.join(target, f);
    const same = existsSync(to) && readFileSync(from).equals(readFileSync(to));
    if (same) continue;
    if (check) drift.push(to);
    else copyFileSync(from, to);
  }
  for (const f of RETIRED) {
    const stale = path.join(target, f);
    if (!existsSync(stale)) continue;
    if (check) drift.push(`${stale} (retired)`);
    else rmSync(stale);
  }
}

// The email logo: PNG bytes as base64 in a TS module (bundlers and the worker both load it without file paths).
const LOGO_MODULE = "packages/adapters/src/mail/logo.generated.ts";
const LOGOS = [
  ["EMAIL_LOGO_LIGHT", "email/anhourmail-logo-email-light.png"],
  ["EMAIL_LOGO_DARK", "email/anhourmail-logo-email-dark.png"],
];
/** A PNG's pixel size from its IHDR chunk; the email shows it at half (the files are 2x). */
function pngSize(buf) {
  if (buf.readUInt32BE(12) !== 0x49484452) throw new Error("not a PNG");
  return { width: buf.readUInt32BE(16) / 2, height: buf.readUInt32BE(20) / 2 };
}
const logoModule = [
  "// SPDX-License-Identifier: AGPL-3.0-only",
  "// Generated by `npm run brand:sync` from packages/ui/assets/brand/email/*.png (scripts/render-email-logo.mjs). Do not",
  "// edit: change the brand source and re-run both.",
  "",
  "export type EmailLogo = { base64: string; width: number; height: number };",
  "",
  ...LOGOS.flatMap(([name, file]) => {
    const buf = readFileSync(path.join(SRC, file));
    const { width, height } = pngSize(buf);
    return [
      `export const ${name}: EmailLogo = {`,
      "  base64:",
      `    "${buf.toString("base64")}",`,
      `  width: ${String(width)},`,
      `  height: ${String(height)},`,
      "};",
      "",
    ];
  }),
].join("\n");
const logoSame = existsSync(LOGO_MODULE) && readFileSync(LOGO_MODULE, "utf8") === logoModule;
if (!logoSame) {
  if (check) drift.push(LOGO_MODULE);
  else writeFileSync(LOGO_MODULE, logoModule);
}

if (drift.length > 0) {
  console.error("Brand assets out of sync — run `npm run brand:sync`:");
  for (const d of drift) console.error(`  ${d}`);
  process.exit(1);
}
console.log(
  check ? "check:brand — app copies and the email logo module match packages/ui/assets/brand." : "brand assets synced.",
);
