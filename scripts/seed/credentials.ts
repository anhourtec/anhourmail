import { writeFileSync } from "node:fs";

import { CLIENT_ENDPOINTS } from "@anhourmail/shared";

/** Writes credentials.md (gitignored; CLAUDE.md rule 50). Never print these values anywhere else. */
export type CredentialRow = { group: string; role: string; email: string; password: string; tryThis: string };

export type CredentialsDoc = {
  urls: { label: string; url: string }[];
  rows: CredentialRow[];
  special: { label: string; detail: string }[];
  mailClient: { address: string; appPassword: string; host: string; imapPort: number; smtpPort: number } | null;
  infra: { label: string; value: string }[];
};

const table = (rows: CredentialRow[]) =>
  [
    "| Role | Email | Password | What to try |",
    "| --- | --- | --- | --- |",
    ...rows.map((r) => `| ${r.role} | \`${r.email}\` | \`${r.password}\` | ${r.tryThis} |`),
  ].join("\n");

export function writeCredentials(path: string, doc: CredentialsDoc): void {
  const groups = [...new Set(doc.rows.map((r) => r.group))];
  const prod = CLIENT_ENDPOINTS.filter((e) => e.protocol === "IMAP" || e.protocol === "SMTP");
  const md = `# Local credentials

> **Local development only. Never commit. Never reuse these passwords.**
> Generated by \`npm run db:seed\` at ${new Date().toISOString()}. Re-running the seed rewrites this file.

## 1. URLs

| What | URL |
| --- | --- |
${doc.urls.map((u) => `| ${u.label} | ${u.url} |`).join("\n")}

${groups.map((g, i) => `## ${i + 2}. ${g}\n\n${table(doc.rows.filter((r) => r.group === g))}`).join("\n\n")}

## ${groups.length + 2}. Special states

${doc.special.map((s) => `- **${s.label}:** ${s.detail}`).join("\n")}

## ${groups.length + 3}. Mail client settings (local)

${
  doc.mailClient
    ? `| Setting | Value |
| --- | --- |
| Username | \`${doc.mailClient.address}\` |
| App password | \`${doc.mailClient.appPassword}\` |
| IMAP | \`${doc.mailClient.host}\` port \`${doc.mailClient.imapPort}\`, SSL/TLS (self-signed in dev — accept the certificate) |
| SMTP | \`${doc.mailClient.host}\` port \`${doc.mailClient.smtpPort}\`, SSL/TLS (self-signed in dev) |

Production equivalents: ${prod.map((e) => `${e.protocol} ${e.host}:${e.port} ${e.security}`).join("; ")}.`
    : "Run `npm run db:seed -- --demo` to create an app password."
}

## ${groups.length + 4}. Infra

| What | Value |
| --- | --- |
${doc.infra.map((i) => `| ${i.label} | \`${i.value}\` |`).join("\n")}

## ${groups.length + 5}. Reset

\`npm run dev:reset\` wipes the Docker volumes, restarts the stack, runs migrations and seeds with \`--demo\`
(this file is rewritten with new passwords).
`;
  writeFileSync(path, md, { mode: 0o600 });
}
