/**
 * Rebuilds the disposable-email data (ADR-0033): `packages/adapters/src/disposable-email/data.generated.ts`.
 *
 * 1. Downloads `disposable_email_blocklist.conf` from disposable-email-domains/disposable-email-domains (CC0) at the
 *    upstream's latest commit, and records that commit.
 * 2. Resolves every listed domain's mail servers (MX, else the domain itself) to IPv4 addresses through public
 *    resolvers, 64 lookups at a time, 2.5 s each.
 * 3. Keeps the addresses that receive mail for at least MIN_DOMAINS listed domains, unless any of their mail-server
 *    names is on a shared provider's suffix (`SHARED_MAIL_SUFFIXES` in `shared-hosts.ts`) or the address is in a
 *    shared or reserved range (`isSharedOrReservedIp`): those serve real people too.
 *
 * Development only (it reaches the internet: GitHub and public DNS). Review the diff before committing: the address
 * list is short enough to read. Run monthly, or when a missed service is reported.
 *
 *   npx tsx scripts/disposable-email-update.ts
 */
import { writeFileSync } from "node:fs";
import { Resolver } from "node:dns/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { isSharedMailHost, isSharedOrReservedIp } from "../packages/adapters/src/disposable-email/shared-hosts";

const REPO = "disposable-email-domains/disposable-email-domains";
const FILE = "disposable_email_blocklist.conf";
const MIN_DOMAINS = 5;
const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  "../packages/adapters/src/disposable-email/data.generated.ts",
);

const commitRes = await fetch(`https://api.github.com/repos/${REPO}/commits?per_page=1`, {
  headers: { accept: "application/vnd.github+json" },
});
if (!commitRes.ok) throw new Error(`GitHub commits: HTTP ${String(commitRes.status)}`);
const [latest] = (await commitRes.json()) as { sha: string }[];
if (!latest) throw new Error("GitHub commits: empty answer");
const commit = latest.sha;
const listRes = await fetch(`https://raw.githubusercontent.com/${REPO}/${commit}/${FILE}`);
if (!listRes.ok) throw new Error(`blocklist: HTTP ${String(listRes.status)}`);
const domains = [
  ...new Set(
    (await listRes.text())
      .split("\n")
      .map((l) => l.trim().toLowerCase())
      .filter((l) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(l)),
  ),
].sort();
if (domains.length < 1000) throw new Error(`blocklist looks wrong: ${String(domains.length)} domains`);

const resolver = new Resolver({ timeout: 2500, tries: 1 });
resolver.setServers(["1.1.1.1", "8.8.8.8"]);

async function pool<T>(items: readonly T[], fn: (item: T) => Promise<void>, size = 64): Promise<void> {
  let i = 0;
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (i < items.length) {
        const item = items[i++];
        if (item !== undefined) await fn(item);
      }
    }),
  );
}

/** domain -> its mail-server names (MX, or the domain itself without MX). */
const mxOf = new Map<string, string[]>();
await pool(domains, async (d) => {
  try {
    const mx = (await resolver.resolveMx(d)).map((m) => m.exchange.toLowerCase().replace(/\.$/, "")).filter(Boolean);
    mxOf.set(d, mx.length ? mx : [d]);
  } catch {
    mxOf.set(d, []);
  }
});
const hosts = [...new Set([...mxOf.values()].flat())];
const ipsOf = new Map<string, string[]>();
await pool(hosts, async (h) => {
  try {
    ipsOf.set(h, await resolver.resolve4(h));
  } catch {
    ipsOf.set(h, []);
  }
});

const domainsByIp = new Map<string, Set<string>>();
const sharedIps = new Set<string>();
for (const [d, mx] of mxOf) {
  for (const h of mx) {
    for (const ip of ipsOf.get(h) ?? []) {
      if (isSharedMailHost(h)) sharedIps.add(ip);
      const set = domainsByIp.get(ip) ?? new Set<string>();
      set.add(d);
      domainsByIp.set(ip, set);
    }
  }
}
const ips = [...domainsByIp]
  .filter(([ip, ds]) => ds.size >= MIN_DOMAINS && !sharedIps.has(ip) && !isSharedOrReservedIp(ip))
  .map(([ip]) => ip)
  .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

const chunk = (list: readonly string[]): string => list.join("\n");
const body = `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/disposable-email-update.ts — do not edit by hand (ADR-0033).
// Domains: ${REPO} (${FILE}, CC0 1.0) at ${commit}.
// Mail servers: IPv4 addresses receiving mail for at least ${String(MIN_DOMAINS)} of those domains, shared providers excluded.

/** Where the data came from and how much of it there is. */
export const DISPOSABLE_SOURCE = {
  repository: "${REPO}",
  commit: "${commit}",
  generated: "${new Date().toISOString().slice(0, 10)}",
  domains: ${String(domains.length)},
  mailServers: ${String(ips.length)},
} as const;

/** Disposable domains, one per line. */
export const DISPOSABLE_DOMAINS = \`
${chunk(domains)}
\`;

/** IPv4 addresses of mail servers that receive for disposable domains, one per line. */
export const DISPOSABLE_MAIL_SERVERS = \`
${chunk(ips)}
\`;
`;
writeFileSync(OUT, body);
console.log(
  `wrote ${OUT}: ${String(domains.length)} domains, ${String(ips.length)} mail-server addresses (commit ${commit.slice(0, 7)})`,
);
